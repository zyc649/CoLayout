"""Native guard generation stays in the established private-preview workflow."""

from math import ceil
from ..model import LiteError, digest
from ..actions import dbu
from ..guard_tools import catalog, generate
from ..regions.query import object_bounds
from ..editor import projected
from .common import direct_objects


def templates(profile):
    result = []
    for row in catalog(profile):
        template = row['template']
        scale = profile.dbu_per_micron
        result.append(
            {
                'id': template.get('id') or digest(template)[:20],
                'label': row['label'],
                'kind': 'recipe'
                if template.get('schema_version') == 'colayout-mpp-recipe-2'
                else 'native_template',
                'minimum_main_path_side_um': template.get('min_side_dbu', 0) / scale or None,
                'minimum_open_segment_um': template.get('min_length_dbu', 0) / scale or None,
                'supported_shapes': ['rectangular_ring', 'open_path_90'],
                'bounds_semantics': 'explicit bounds are the native main-path rectangle; actual outer bounds come from generation',
                'points_semantics': 'points_um are ordered open horizontal/vertical main-path vertices; actual outer material is generated by the same UI template/recipe',
                'template': template,
            }
        )
    return result


def _request(source, profile, scope, args, rules):
    row = next((r for r in templates(profile) if r['id'] == args.template_id), None)
    if row is None:
        raise LiteError('UNKNOWN_GUARD_TEMPLATE', '请使用 rules.guard_templates 中的 ID。')
    template = row['template']
    scale = profile.dbu_per_micron
    if args.points_um is not None:
        return row, 'create_mpp', {'points': args.points_um, 'template': template, 'net_intent': args.net_intent}
    if args.bounds_um is not None:
        a, b, c, d = [dbu(v, profile) for v in args.bounds_um]
    else:
        from ..editor import Editor

        editor = Editor(source, profile, scope_id=scope)
        objects = direct_objects(editor, args.uids)
        boxes = [object_bounds(source, obj, profile) for obj in objects.values()]
        if any(bounds is None for bounds in boxes):
            raise LiteError('OBJECT_BOUNDS_MISSING')
        if row['kind'] != 'recipe' and args.clearance is None:
            raise LiteError(
                'GUARD_CLEARANCE_REQUIRED',
                '此原生模板未提供可发现的截面范围；请明确 main-path bounds 或 clearance。',
            )
        reach = template.get('width', 0) / 2
        for part in template.get('parts', []):
            half = (
                (template.get('width', 0) / 2 + max(0, -part['enclosure']))
                if part['kind'] == 'enclosurePath'
                else max(part.get('width', 0), part.get('length', 0)) / 2
            )
            reach = max(reach, half + abs(part.get('separation', 0)))
        guard_layers = {tuple(part['lpp'])[0] for part in template.get('parts', [])}
        clearance = (
            dbu(args.clearance, profile)
            if args.clearance is not None
            else max(
                [profile.grid]
                + [
                    r.value * scale
                    for r in (rules.rules if rules else ())
                    if r.enabled and r.kind == 'spacing' and r.layer in guard_layers
                ]
            )
        )
        margin = ceil((reach + clearance) / profile.grid) * profile.grid
        a, b = min(x[0][0] for x in boxes) - margin, min(x[0][1] for x in boxes) - margin
        c, d = max(x[1][0] for x in boxes) + margin, max(x[1][1] for x in boxes) + margin
    if a >= c or b >= d:
        raise LiteError('INVALID_GUARD_BOUNDS')
    return row, 'create_guard', {
            'x': a / scale,
            'y': b / scale,
            'width': (c - a) / scale,
            'height': (d - b) / scale,
            'template': template,
            'net_intent': args.net_intent,
        }


def prepare(source, profile, scope, args, rules, adapter, progress):
    row, action, params = _request(source, profile, scope, args, rules)
    result = generate(source,profile,scope,adapter,action,params,progress=progress)
    scale = profile.dbu_per_micron
    uid, candidate = result
    obj = projected(candidate)[uid]
    roles = {r['layer']: r.get('material') for r in profile.layers if r['purpose'] == 'drawing'}
    layers = {part['lpp'][0] for part in obj.mpp.parts if part.get('lpp')}
    if obj.mpp.master:
        layers.add(obj.mpp.master.lpp[0])
    warnings = []
    well_layers=sorted(layer for layer in layers if roles.get(layer)=='nwell')
    if well_layers:
        warnings.append(
            {
                'code': 'NGR_CHECK_NWELL_GAP',
                'severity': 'warning',
                'category': 'operation_reminder',
                'message': '保护环包含井层 '+', '.join(well_layers)+'；请结合内部器件补齐完整井区，再检查整个设计。孤立环的井宽/孔洞报告需结合该使用上下文判断。',
                'layers': well_layers,
                'drc_violation_confirmed': False,
            }
        )
    bounds = object_bounds(candidate, obj, profile)
    return candidate, {
        'created_uids': [uid],
        'template_id': row['id'],
        'form': 'open_path_90' if action=='create_mpp' else 'rectangular_ring',
        'bounds_um': [v / scale for p in bounds for v in p],
        'warnings': warnings,
        'net_intent': args.net_intent,
        'native_generation': 'private preview; source layout not committed',
    }
